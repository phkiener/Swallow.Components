namespace Swallow.Components.Actions;

/// <summary>
/// The variant of a button.
/// </summary>
public enum ButtonVariant
{
    /// <summary>
    /// A highlighted button, drawing attention.
    /// </summary>
    Primary = 1,

    /// <summary>
    /// The default button.
    /// </summary>
    Default = 2,

    /// <summary>
    /// A less pronounced button, shown only as text without decoration.
    /// </summary>
    Text = 3,
}
